#!/usr/bin/env python3
"""Generate the exact SDL C export table from public headers and the built archive."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess


DECLARATION = re.compile(
    r"\bSDL_DECLSPEC\b(?:(?!;).)*?\bSDLCALL\s+(SDL_[A-Za-z0-9_]+)\s*\(",
    re.DOTALL,
)
COMMENTS = re.compile(r"/\*.*?\*/|//[^\n]*", re.DOTALL)
FUNCTION_TYPES = {"T", "W"}
ACTIVE_USE = re.compile(r"\b(SDL_[A-Za-z0-9_]+)\s*\(")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def public_functions(headers_root, compiler, compiler_flags):
    names = {}
    used_headers = []
    unavailable_headers = []
    for header in sorted(headers_root.glob("SDL*.h")):
        if header.name == "SDL_internal.h":
            continue
        source = COMMENTS.sub(" ", header.read_text(encoding="utf-8", errors="strict"))
        raw = {name for name in DECLARATION.findall(source) if not name.endswith("_REAL")}
        if not raw:
            continue
        include_source = f"#define SDL_MAIN_HANDLED\n#include <SDL3/{header.name}>\n"
        try:
            output = subprocess.run(
                [compiler, *compiler_flags, "-E", "-P", "-x", "c", "-"],
                input=include_source,
                check=True,
                capture_output=True,
                text=True,
            ).stdout
        except subprocess.CalledProcessError as error:
            unavailable_headers.append({"header": header.name, "reason": error.stderr.strip().splitlines()[-1] if error.stderr else "preprocessor failed"})
            continue
        active = raw & set(ACTIVE_USE.findall(output))
        if active:
            used_headers.append(header)
            for name in active:
                names.setdefault(name, set()).add(header.name)
    return names, used_headers, unavailable_headers


def archive_functions(archive, nm):
    output = subprocess.run(
        [nm, "-g", "--defined-only", str(archive)],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    names = set()
    for line in output.splitlines():
        fields = line.split()
        if len(fields) >= 3 and fields[-2] in FUNCTION_TYPES:
            names.add(fields[-1].split("@", 1)[0])
    return names


def generate(headers_root, archive, output, manifest, nm, compiler, compiler_flags):
    declared, used_headers, unavailable_headers = public_functions(headers_root, compiler, compiler_flags)
    archived = archive_functions(archive, nm)
    exports = sorted(set(declared) & archived)
    if not exports:
        raise RuntimeError("no SDL public function declarations are defined by the archive")

    lines = [
        "/* Generated by scripts/generate-sdl-symbols.py; do not edit. */",
        "#ifndef SWITCHCRAFT_SDL_SYMBOLS_GENERATED_H",
        "#define SWITCHCRAFT_SDL_SYMBOLS_GENERATED_H",
        "",
        "#include <SDL3/SDL.h>",
    ]
    lines.extend(f"#include <SDL3/{header.name}>" for header in used_headers if header.name != "SDL.h")
    lines.extend(["", "#define SC_SDL_SYMBOLS(X) \\"])
    for index, name in enumerate(exports):
        suffix = " \\" if index + 1 < len(exports) else ""
        lines.append(f"    X({name}){suffix}")
    lines.extend(["", "#endif", ""])
    content = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")

    record = {
        "headers_root": headers_root.as_posix(),
        "archive": archive.as_posix(),
        "archive_sha256": digest(archive),
        "nm": Path(nm).name,
        "compiler": Path(compiler).name,
        "compiler_flags": compiler_flags,
        "preprocessor_unavailable_headers": unavailable_headers,
        "public_header_count": len(used_headers),
        "declared_public_function_count": len(declared),
        "archive_function_count": len(archived),
        "matched_export_count": len(exports),
        "generated_header_sha256": hashlib.sha256(content.encode("utf-8")).hexdigest(),
        "excluded_public_but_unavailable": sorted(set(declared) - archived),
        "exports": exports,
    }
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    return record


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--headers", type=Path, default=root / ".deps/sdl3/include/SDL3")
    parser.add_argument("--archive", type=Path, default=root / ".deps/sdl3/lib/libSDL3.a")
    parser.add_argument("--output", type=Path, default=root / "build/sdl_symbols_generated.h")
    parser.add_argument("--manifest", type=Path, default=root / "build/sdl_symbols_generated.json")
    parser.add_argument("--nm", default=shutil.which("nm") or "nm")
    parser.add_argument("--cc", default="cc", help="target C compiler used to evaluate conditional public declarations")
    parser.add_argument("--define", action="append", default=["__SWITCH__"], help="target preprocessor define (repeatable)")
    parser.add_argument("--include", type=Path, action="append", default=None, help="include directory (repeatable)")
    args = parser.parse_args()
    include_dirs = args.include if args.include is not None else [args.headers.parent, root / ".deps/vk-headers/include"]
    compiler_flags = [f"-I{path}" for path in include_dirs]
    compiler_flags.extend(f"-D{value}" for value in args.define)
    result = generate(args.headers, args.archive, args.output, args.manifest, args.nm, args.cc, compiler_flags)
    print(
        "SDL public functions declared={declared_public_function_count} archive={archive_function_count} "
        "matched={matched_export_count} header_sha256={generated_header_sha256}".format(**result)
    )


if __name__ == "__main__":
    main()
